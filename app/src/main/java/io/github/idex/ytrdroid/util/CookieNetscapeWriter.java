package io.github.idex.ytrdroid.util;

import android.webkit.CookieManager;

import java.io.BufferedReader;
import java.io.File;
import java.io.FileReader;
import java.io.FileWriter;
import java.io.IOException;
import java.util.HashSet;
import java.util.Set;

public final class CookieNetscapeWriter {

    private CookieNetscapeWriter() {}

    /**
     * Reads all cookies from the system CookieManager for YouTube and Google domains,
     * formats them into standard Netscape cookies.txt format, and saves them to destFile.
     */
    public static boolean saveYouTubeCookies(File destFile) {
        if (destFile == null) return false;
        try {
            CookieManager cm = CookieManager.getInstance();
            cm.flush();
            String ytCookies = cm.getCookie("https://www.youtube.com");
            String mYtCookies = cm.getCookie("https://m.youtube.com");
            String googleCookies = cm.getCookie("https://accounts.google.com");

            String netscapeText = formatToNetscape(ytCookies, mYtCookies, googleCookies);
            if (netscapeText == null || netscapeText.trim().isEmpty()) {
                return false;
            }

            File parent = destFile.getParentFile();
            if (parent != null && !parent.exists()) {
                parent.mkdirs();
            }

            try (FileWriter writer = new FileWriter(destFile)) {
                writer.write(netscapeText);
                return true;
            }
        } catch (Exception e) {
            return false;
        }
    }

    /**
     * Formats cookie strings into a standard Netscape cookies.txt format.
     */
    public static String formatToNetscape(String ytCookies, String mYtCookies, String googleCookies) {
        StringBuilder sb = new StringBuilder();
        sb.append("# Netscape HTTP Cookie File\n");
        sb.append("# http://curl.haxx.se/rfc/cookie_spec.html\n");
        sb.append("# Generated by ytrd YouTube Login\n\n");

        long expiry = (System.currentTimeMillis() / 1000L) + (365L * 24L * 3600L); // 1 year
        Set<String> writtenKeys = new HashSet<>();

        appendDomainCookies(sb, ".youtube.com", ytCookies, expiry, writtenKeys);
        appendDomainCookies(sb, ".youtube.com", mYtCookies, expiry, writtenKeys);
        appendDomainCookies(sb, ".google.com", googleCookies, expiry, writtenKeys);

        if (writtenKeys.isEmpty()) {
            return null;
        }
        return sb.toString();
    }

    private static void appendDomainCookies(StringBuilder sb, String domain, String cookieString,
                                            long expiry, Set<String> writtenKeys) {
        if (cookieString == null || cookieString.trim().isEmpty()) return;
        String[] pairs = cookieString.split(";");
        for (String pair : pairs) {
            String trimmed = pair.trim();
            int eq = trimmed.indexOf('=');
            if (eq > 0) {
                String name = trimmed.substring(0, eq).trim();
                String value = trimmed.substring(eq + 1).trim();
                String key = domain + ":" + name;
                if (!name.isEmpty() && !writtenKeys.contains(key)) {
                    writtenKeys.add(key);
                    sb.append(domain).append("\t")
                            .append("TRUE").append("\t")
                            .append("/").append("\t")
                            .append("TRUE").append("\t")
                            .append(expiry).append("\t")
                            .append(name).append("\t")
                            .append(value).append("\n");
                }
            }
        }
    }

    /**
     * Checks if the cookies file contains authenticated login cookies (e.g. LOGIN_INFO or SID).
     */
    public static boolean hasLoginCookies(File cookiesFile) {
        if (cookiesFile == null || !cookiesFile.isFile() || cookiesFile.length() == 0) {
            return false;
        }
        try (BufferedReader reader = new BufferedReader(new FileReader(cookiesFile))) {
            String line;
            while ((line = reader.readLine()) != null) {
                if (line.contains("LOGIN_INFO") || line.contains("SID") || line.contains("SAPISID")) {
                    return true;
                }
            }
        } catch (IOException ignored) {}
        return false;
    }
}
